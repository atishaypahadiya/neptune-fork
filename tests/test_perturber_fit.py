@pytest.mark.slow
@pytest.mark.parametrize("a_fixed", [BODE_A_AU, None], ids=["le_verrier", "free_a"])
def test_m5a_multistart_on_synthetic_data(ctx, seed0, a_fixed):
    """Seed 0, 24 λ₀ starts. The best fit is a genuine minimum inside the M5 prior and fits to
    the noise (post-1781 RMS ≤ 1.5σ). Compared with the true Neptune planted and Uranus refitted
    (χ² 75.22): free a must do at least as well (truth is inside its model family, so this
    checks the multistart reached the global region); Le Verrier mode cannot represent a = 30 AU,
    yet must be statistically indistinguishable (Δχ² < 4; measured +0.34).

    Measured (e ≤ 0.3 bound): Le Verrier m 20.3 M⊕, e 0.265, χ²/dof 0.956, RMS 2.86″, 3 minima,
    1846-09-23 longitude −6.87° from Neptune; free a m 15.5 M⊕, a 27.3 AU, e 0.165, χ²/dof 0.922,
    RMS 2.78″, 7 minima, +11.77°. (Unbounded, before the fix: 6 and 4 minima, same best fits.)
    See docs/notes/M5.md for why the longitudes miss (a flat likelihood / fixed a).
    """
    obs, _, inc_raan, th_nep = seed0
    r = fit_perturber_multistart(obs, ctx, inc_raan, a_fixed_au=a_fixed, n_workers=N_WORKERS)
    assert len(r.fits) == N_LAM0_STARTS and r.status_counts()["failed"] == 0
    best = r.best
    assert best.status == "converged" and best.in_m5_prior
    assert all(f.theta[8] <= 0.3 + 1e-12 for f in r.fits)  # the e prior bound holds everywhere
    post = obs.source == "synthetic_post_discovery"
    assert np.sqrt(np.mean(best.residual_rad[post] ** 2)) * ARC <= 1.5 * SIGMA_POST_DISCOVERY_ARCSEC
    planted = fit_uranus_elements(obs, ctx, inc_raan, fixed_perturber_theta=th_nep)
    if a_fixed is None:
        assert best.chi2 <= planted.chi2 + 1e-6  # measured 71.91 vs 75.22
    else:
        assert best.chi2 - planted.chi2 < 4.0  # measured 75.56 vs 75.22
    assert 2 <= len(r.minima) <= 12


@pytest.mark.slow
def test_m5a_free_a_noise_free_recovers_neptune(ctx, seed0):
    """Noise-free Horizons truth (real 3-D Neptune in the data, planar perturber in the model):
    free-a multistart lands on Neptune, so the model is unbiased and the seed-0 offsets are noise.
    ~60 s: with the starts in a process pool the slowest single LM run sets the wall time, and
    noise-free runs take many steps toward χ² ≈ 0. Measured m 17.14 M⊕ (true 17.15), a 30.24 AU
    (osculating 30.22), e 0.004, 1846-09-23 longitude −0.07° from Neptune.
    """
    obs, truth, inc_raan, th_nep = seed0
    clean = LongitudeObservations(obs.jd_tdb, truth, obs.sigma_rad, obs.source)
    r = fit_perturber_multistart(clean, ctx, inc_raan, n_workers=N_WORKERS)
    best = r.best
    assert abs(best.mass_earth - 10 ** th_nep[0]) < 0.5
    assert abs(best.theta[7] - th_nep[1]) < 0.3 and best.theta[8] < 0.02
    g, nep = perturber_geocentric_longitude(best.theta, ctx), true_neptune_geocentric_longitude()
    dlon_deg = math.degrees(wrap_rad(g.lon_ecl_of_date_rad - nep.lon_ecl_of_date_rad))
    assert abs(dlon_deg) < 0.25
