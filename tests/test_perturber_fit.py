def _fake(chi2, theta_p, success=True):
    theta = np.concatenate([[19.2, 0.047, 0.0136, 1.29, 3.0, 1.7], theta_p])
    return PerturberFit(theta, np.zeros(3), chi2, 80, success, 10, 0.0)


def test_classify_and_group_minima():
    no_pert = 1000.0
    fits = [
        _fake(70.0, [1.2, 30.0, 0.01, 1.0, 3.00]),
        _fake(70.2, [1.21, 30.5, 0.01, 1.0, 3.02]),  # same valley (within MINIMUM_TOL)
        _fake(71.0, [1.2, 30.0, 0.01, 1.0, 3.00]),  # Δχ² > 0.5 → distinct
        _fake(95.0, [1.6, 20.7, 0.12, 1.0, 0.44]),  # different λ₀ → distinct
        _fake(1750.0, [0.5, 40.0, 0.949, 1.0, 2.0]),  # against the e guard
        _fake(999.5, [0.1, 40.0, 0.2, 1.0, 2.0]),  # perturber does nothing
        _fake(60.0, [1.2, 30.0, 0.01, 1.0, 3.0], success=False),
    ]
    status = [classify(f, no_pert) for f in fits]
    assert status == ["converged"] * 4 + ["stalled_at_guard", "null", "failed"]
    from dataclasses import replace

    fits = [replace(f, status=s) for f, s in zip(fits, status, strict=True)]
    minima = group_minima(fits, free_a=True)
    assert [m.n_starts for m in minima] == [2, 1, 1]
    assert [m.best.chi2 for m in minima] == [70.0, 71.0, 95.0]
    assert len(group_minima(fits, free_a=False)) == 3


def test_le_verrier_mode_recovers_model_perturber_from_one_start(ctx, model_obs):
    """Noise-free data generated by the model itself, a held at its true value, one λ₀ start
    17° off: LM must land on the generating perturber and Uranus."""
    th = THETA_MODEL
    start = np.array([th[10] + math.radians(17.0)])
    r = fit_perturber_multistart(model_obs, ctx, (th[2], th[3]), a_fixed_au=th[7],
                                 lam0_starts_rad=start)  # fmt: skip
    f = r.fits[0]
    assert f.status == "converged" and f.chi2 < 1e-6
    assert abs(f.theta[6] - th[6]) < 1e-4 and abs(f.theta[8] - th[8]) < 1e-4
    assert abs(wrap_rad(f.theta[10] - th[10])) < 1e-4
    assert abs(f.theta[0] - th[0]) < 1e-5 and f.theta[7] == th[7]


def test_free_a_recovers_model_perturber_from_one_start(ctx, model_obs):
    th = THETA_MODEL
    start = np.array([th[10] - math.radians(10.0)])
    r = fit_perturber_multistart(model_obs, ctx, (th[2], th[3]), lam0_starts_rad=start)
    f = r.fits[0]
    assert f.status == "converged" and f.chi2 < 1e-4
    assert abs(f.theta[7] - th[7]) < 0.01 and abs(f.theta[6] - th[6]) < 1e-3


def test_multistart_grid_and_bookkeeping(ctx, model_obs):
    th = THETA_MODEL
    starts = np.radians([0.0, 180.0])
    r = fit_perturber_multistart(model_obs, ctx, (th[2], th[3]), a_fixed_au=th[7],
                                 lam0_starts_rad=starts)  # fmt: skip
    assert r.mode == "le_verrier" and len(r.fits) == 2
    assert [f.start_lam0_rad for f in r.fits] == starts.tolist()
    assert sum(r.status_counts().values()) == 2
    assert sum(m.n_starts for m in r.minima) == r.status_counts()["converged"]
    assert N_LAM0_STARTS == 24


